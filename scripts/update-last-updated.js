#!/usr/bin/env node

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

// Get the current date in a readable format
const now = new Date();
const options = { 
  year: 'numeric', 
  month: 'long', 
  day: 'numeric' 
};
const formattedDate = now.toLocaleDateString('en-US', options);

// Create the content for the last updated file
const content = `// This file is automatically generated - do not edit manually
export const LAST_UPDATED = "${formattedDate}";
`;

// Write to the constants directory
const outputPath = path.join(__dirname, '..', 'src', 'constants', 'lastUpdated.ts');
fs.writeFileSync(outputPath, content);

console.log(`✅ Last updated date set to: ${formattedDate}`);
